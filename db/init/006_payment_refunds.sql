-- 新增核對與退款帳務，不轉換或刪除既有付款。
ALTER TABLE payment_record ADD COLUMN IF NOT EXISTS operation_version bigint NOT NULL DEFAULT 0;
ALTER TABLE payment_record ADD COLUMN IF NOT EXISTS reconciliation_status varchar(30) NOT NULL DEFAULT 'unreviewed';
ALTER TABLE payment_record ADD COLUMN IF NOT EXISTS reconciliation_note text;
ALTER TABLE payment_record ADD COLUMN IF NOT EXISTS reconciliation_reference varchar(100);
ALTER TABLE payment_record ADD COLUMN IF NOT EXISTS reconciled_by integer REFERENCES app_user(id);
ALTER TABLE payment_record ADD COLUMN IF NOT EXISTS reconciled_at timestamptz;

CREATE TABLE IF NOT EXISTS refund_record (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_record_id integer NOT NULL REFERENCES payment_record(id),
    amount numeric(12,2) NOT NULL CHECK (amount > 0),
    status varchar(20) NOT NULL DEFAULT 'requested'
        CHECK (status IN ('requested','approved','rejected','completed','simulated')),
    idempotency_key uuid NOT NULL UNIQUE,
    reason varchar(1000) NOT NULL,
    decision_note varchar(1000),
    external_reference varchar(100),
    requested_by integer NOT NULL REFERENCES app_user(id),
    decided_by integer REFERENCES app_user(id),
    completed_by integer REFERENCES app_user(id),
    requested_at timestamptz NOT NULL,
    decided_at timestamptz,
    completed_at timestamptz,
    operation_version bigint NOT NULL DEFAULT 0 CHECK (operation_version >= 0),
    CHECK (status <> 'completed' OR (external_reference IS NOT NULL AND completed_at IS NOT NULL AND completed_by IS NOT NULL)),
    CHECK (status NOT IN ('approved','rejected','completed','simulated') OR (decided_at IS NOT NULL AND decided_by IS NOT NULL)),
    UNIQUE (payment_record_id, external_reference)
);
CREATE INDEX IF NOT EXISTS idx_refund_payment ON refund_record(payment_record_id, id);
