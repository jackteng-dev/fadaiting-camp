CREATE TABLE IF NOT EXISTS app_user (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(20) NOT NULL UNIQUE,
    password varchar(128),
    first_name varchar(50) DEFAULT '',
    last_name varchar(50) DEFAULT '',
    email varchar(128) DEFAULT '',
    telephone varchar(32) DEFAULT '',
    role varchar(50) DEFAULT '',
    user_pic varchar(512) DEFAULT '',
    last_login_time timestamp,
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now(),
    is_stop varchar(1) NOT NULL DEFAULT 'F'
);

CREATE TABLE IF NOT EXISTS category (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name varchar(32) NOT NULL,
    category_alias varchar(32) NOT NULL,
    create_user integer NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    create_time timestamp NOT NULL DEFAULT now(),
    update_time timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS article (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(30) NOT NULL,
    content text NOT NULL,
    cover_img varchar(512) NOT NULL,
    state varchar(10) NOT NULL DEFAULT '草稿',
    category_id integer REFERENCES category(id) ON DELETE SET NULL,
    create_user integer NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    create_time timestamp NOT NULL DEFAULT now(),
    update_time timestamp NOT NULL DEFAULT now(),
    CONSTRAINT article_state_check CHECK (state IN ('已發布', '草稿'))
);

CREATE TABLE IF NOT EXISTS camp_site (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    slug varchar(100) NOT NULL UNIQUE,
    short_description varchar(255) DEFAULT '',
    full_description text DEFAULT '',
    address_line varchar(255) DEFAULT '',
    city varchar(100) DEFAULT '',
    county varchar(100) DEFAULT '',
    postal_code varchar(20) DEFAULT '',
    latitude numeric(10, 7),
    longitude numeric(10, 7),
    contact_name varchar(100) DEFAULT '',
    contact_phone varchar(32) DEFAULT '',
    contact_email varchar(128) DEFAULT '',
    facebook_url varchar(512) DEFAULT '',
    check_in_time varchar(20) DEFAULT '14:00',
    check_out_time varchar(20) DEFAULT '11:00',
    booking_notice text DEFAULT '',
    refund_policy text DEFAULT '',
    is_active boolean NOT NULL DEFAULT true,
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS camp_zone (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camp_site_id integer NOT NULL REFERENCES camp_site(id) ON DELETE CASCADE,
    name varchar(100) NOT NULL,
    slug varchar(100) NOT NULL,
    zone_type varchar(30) NOT NULL DEFAULT 'tent',
    description text DEFAULT '',
    sort_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now(),
    UNIQUE (camp_site_id, slug)
);

CREATE TABLE IF NOT EXISTS camp_unit (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camp_site_id integer NOT NULL REFERENCES camp_site(id) ON DELETE CASCADE,
    zone_id integer NOT NULL REFERENCES camp_zone(id) ON DELETE CASCADE,
    name varchar(100) NOT NULL,
    unit_type varchar(30) NOT NULL DEFAULT 'tent_site',
    description text DEFAULT '',
    max_guests integer NOT NULL DEFAULT 4,
    max_vehicles integer NOT NULL DEFAULT 1,
    max_tents integer NOT NULL DEFAULT 1,
    has_shelter boolean NOT NULL DEFAULT false,
    electricity_available boolean NOT NULL DEFAULT false,
    private_bathroom boolean NOT NULL DEFAULT false,
    quantity integer NOT NULL DEFAULT 1,
    sort_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS rate_plan (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camp_site_id integer NOT NULL REFERENCES camp_site(id) ON DELETE CASCADE,
    camp_unit_id integer NOT NULL REFERENCES camp_unit(id) ON DELETE CASCADE,
    name varchar(100) NOT NULL,
    day_type varchar(20) NOT NULL DEFAULT 'weekday',
    base_price numeric(10, 2) NOT NULL,
    extra_person_price numeric(10, 2) NOT NULL DEFAULT 0,
    cleaning_fee numeric(10, 2) NOT NULL DEFAULT 0,
    description text DEFAULT '',
    is_active boolean NOT NULL DEFAULT true,
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS availability (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camp_site_id integer NOT NULL REFERENCES camp_site(id) ON DELETE CASCADE,
    camp_unit_id integer NOT NULL REFERENCES camp_unit(id) ON DELETE CASCADE,
    available_date date NOT NULL,
    total_quantity integer NOT NULL DEFAULT 1,
    reserved_quantity integer NOT NULL DEFAULT 0,
    blocked_quantity integer NOT NULL DEFAULT 0,
    price_override numeric(10, 2),
    is_closed boolean NOT NULL DEFAULT false,
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now(),
    UNIQUE (camp_unit_id, available_date)
);

CREATE TABLE IF NOT EXISTS rental_item (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camp_site_id integer NOT NULL REFERENCES camp_site(id) ON DELETE CASCADE,
    name varchar(100) NOT NULL,
    category varchar(30) NOT NULL DEFAULT 'other',
    description text DEFAULT '',
    image_url varchar(1000) DEFAULT '',
    unit_price numeric(10, 2) NOT NULL DEFAULT 0,
    total_quantity integer NOT NULL DEFAULT 0,
    sort_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS booking (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_no varchar(30) NOT NULL UNIQUE,
    camp_site_id integer NOT NULL REFERENCES camp_site(id) ON DELETE RESTRICT,
    member_user_id integer REFERENCES app_user(id) ON DELETE SET NULL,
    status varchar(20) NOT NULL DEFAULT 'pending',
    source varchar(20) NOT NULL DEFAULT 'website',
    check_in_date date NOT NULL,
    check_out_date date NOT NULL,
    nights integer NOT NULL DEFAULT 1,
    guest_count integer NOT NULL DEFAULT 1,
    vehicle_count integer NOT NULL DEFAULT 0,
    subtotal_amount numeric(10, 2) NOT NULL DEFAULT 0,
    adjustment_amount numeric(10, 2) NOT NULL DEFAULT 0,
    total_amount numeric(10, 2) NOT NULL DEFAULT 0,
    paid_amount numeric(10, 2) NOT NULL DEFAULT 0,
    note text DEFAULT '',
    admin_note text DEFAULT '',
    confirm_note text DEFAULT '',
    cancel_reason text DEFAULT '',
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now(),
    CONSTRAINT booking_status_check CHECK (status IN ('pending', 'confirmed', 'cancelled', 'completed'))
);

CREATE TABLE IF NOT EXISTS booking_guest (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id integer NOT NULL UNIQUE REFERENCES booking(id) ON DELETE CASCADE,
    contact_name varchar(100) NOT NULL,
    contact_phone varchar(32) NOT NULL,
    contact_email varchar(128) DEFAULT '',
    emergency_contact_name varchar(100) DEFAULT '',
    emergency_contact_phone varchar(32) DEFAULT '',
    arrival_note text DEFAULT '',
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS booking_item (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id integer NOT NULL REFERENCES booking(id) ON DELETE CASCADE,
    camp_unit_id integer NOT NULL REFERENCES camp_unit(id) ON DELETE RESTRICT,
    rate_plan_id integer REFERENCES rate_plan(id) ON DELETE SET NULL,
    rental_item_id integer REFERENCES rental_item(id) ON DELETE SET NULL,
    item_name varchar(100) NOT NULL,
    quantity integer NOT NULL DEFAULT 1,
    unit_price numeric(10, 2) NOT NULL DEFAULT 0,
    nights integer NOT NULL DEFAULT 1,
    line_total numeric(10, 2) NOT NULL DEFAULT 0,
    created_time timestamp NOT NULL DEFAULT now(),
    modified_time timestamp NOT NULL DEFAULT now()
);

