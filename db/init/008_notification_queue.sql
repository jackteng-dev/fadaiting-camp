-- 舊通知保留原狀，但不自動納入新版發送佇列，避免升級後寄出過時訊息。
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS queue_managed boolean NOT NULL DEFAULT false;
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS event_key varchar(180);
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0);
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS attempt_limit integer NOT NULL DEFAULT 5 CHECK (attempt_limit > 0);
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS next_attempt_at timestamptz;
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS lease_token uuid;
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS lease_until timestamptz;
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS delivery_mode varchar(20);
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS error_code varchar(50);
ALTER TABLE notification_record ADD COLUMN IF NOT EXISTS operation_version bigint NOT NULL DEFAULT 0;
CREATE UNIQUE INDEX IF NOT EXISTS idx_notification_event_key ON notification_record(event_key) WHERE event_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_notification_due ON notification_record(next_attempt_at, id)
    WHERE queue_managed AND channel = 'email' AND status IN ('queued', 'retry_wait');
CREATE INDEX IF NOT EXISTS idx_notification_lease ON notification_record(lease_until) WHERE status = 'processing';
CREATE TABLE IF NOT EXISTS notification_attempt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id integer NOT NULL REFERENCES notification_record(id) ON DELETE CASCADE,
    attempt_number integer NOT NULL,
    lease_token uuid NOT NULL UNIQUE,
    delivery_mode varchar(20) NOT NULL,
    status varchar(30) NOT NULL DEFAULT 'processing',
    error_code varchar(50),
    started_at timestamptz NOT NULL,
    finished_at timestamptz,
    actor_user_id integer,
    actor_name varchar(100) NOT NULL DEFAULT '',
    UNIQUE(notification_id, attempt_number)
);
